NOTE = ("Design units: desktop canvas 1600x900, mobile 900x1600, origin at the canvas centre, y down. w = drawn width. "
        "from = state at scroll progress 0, to = state at 1; win = the part of the progress over which this layer moves. "
        "s scale, r degrees, o opacity. depth = pointer parallax in design px. Generated by a script from the props' "
        "bounding boxes where parts must line up (see the page's note); edit by hand freely, but keep r = 0 and s = 1 "
        "in `from` for those layers or they will no longer fit together at progress 0.")

def fit(page, prop, G, X, Y, dy=0.0):
    """Layer geometry for a prop rendered uncropped: group frame G wide, centred at X, Y."""
    im = Image.open(SRC / page / f'{prop}.png'); F = im.width
    l, t, r, b = im.getbbox()
    return dict(w=round(G * (r - l) / F, 1), x=round(X + G * ((l + r) / 2 / F - 0.5), 1), y=round(Y + G * ((t + b) / 2 / F - 0.5) + dy, 1))

def L(id, prop, w, z, frm, to, win, depth=0, **kw):
    d = dict(id=id, prop=prop, w=w, z=z, depth=depth, **{'from': frm}, to=to, win=win); d.update(kw); return d

def at(g, **extra):  # 'from' state of a fitted layer
    return dict(x=g['x'], y=g['y'], **extra)

