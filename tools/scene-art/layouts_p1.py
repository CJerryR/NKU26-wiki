"""Regenerates src/data/scenes/{experiments,parts,background,attributions}.json  (python3 tools/scene-art/layouts_p1.py).
Re-run python3 tools/pack_scene_atlas.py <page> afterwards if you re-rendered props.
Props rendered on a shared uncropped frame (dish lid/base, plasmid halves,
puzzle pieces) are placed from their bounding boxes, so at progress 0 they sit
exactly where the renderer put them: the lid on its dish, the pieces interlocked."""
import json
