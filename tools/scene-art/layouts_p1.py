def dish_stack(G, X, Y, n, z0, lid_to, base_to, wins, depth):
    """n stacked dishes; each lid lifts in its own window (top lid first)."""
    step = 0.125 * 0.829 / 1.32 * G   # stack pitch 0.125 world, cos 34 deg, frame 2 x 0.66
    layers = []
    for k in range(n):
        gb, gl = fit('experiments', 'dish-base', G, X, Y, -k * step), fit('experiments', 'dish-lid', G, X, Y, -k * step)
        layers.append(L(f'dish-{k}', 'dish-base', gb['w'], z0 + 2 * k, at(gb), base_to[k], [0.3, 0.8], depth))
        layers.append(L(f'lid-{k}', 'dish-lid', gl['w'], z0 + 2 * k + 1, at(gl), lid_to[k], wins[k], depth + 6))
    return layers

