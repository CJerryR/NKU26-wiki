class Missing(Exception):
    pass


def meta(name):
    side = ISL / f'{name}.json'
    if not side.exists():
        raise Missing(name)
    return I.REG[name], json.loads(side.read_text())['pxw']     # px per world unit, as rendered


def sprite(name):
    p = ISL / f'{name}.png'
    if not p.exists():
        raise Missing(name)
    return Image.open(p)


def width(name, band, k):
    im = sprite(name); _, pxw = meta(name)
    return round(im.width / pxw * k * band, 1)


def fit(name, band, k, X, Y, s=1.0):
    """Placement of an uncropped (shared-frame) sprite whose frame is centred at X, Y."""
    im = sprite(name); r, pxw = meta(name)
    G = 2 * r['extent'] * k * band
    l, t, rr, b = im.getbbox()
    w = G * (rr - l) / im.width
    dx = G * ((l + rr) / 2 / im.width - 0.5); dy = G * ((t + b) / 2 / im.width - 0.5 * im.height / im.width)
    return round(w, 1), round(X + s * dx, 1), round(Y + s * dy, 1)


def L(id, prop, w, z, frm, to, win=(0.1, 0.8), depth=12):
    return {'id': id, 'prop': prop, 'w': w, 'z': z, 'depth': depth, 'from': frm, 'to': to, 'win': list(win)}


def isl(id, name, x, y, to, band=1.0, z=3, win=(0.1, 0.8), depth=12, k=K, **frm):
    """A cropped island layer at x, y; `to` is a dict of end values."""
    return L(id, 'i-' + name, width(name, band, k), z, dict(x=x, y=y, **frm), to, win, depth)


def T(x, y, s=1.08, r=0.0, o=None):
    d = dict(x=x, y=y, s=s, r=r)
    if o is not None:
        d['o'] = o
    return d


def legacy(page, kind, ids=None):
    return [dict(l) for l in LEGACY[page][kind]['layers'] if ids is None or l['id'] in ids]


