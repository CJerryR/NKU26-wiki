def write(page):
    cur = ROOT / 'src' / 'data' / 'scenes' / f'{page}.json'
    if cur.exists() and 'subpage_openings.py' in json.loads(cur.read_text()).get('note', ''):
        return 'skipped: owned by tools/scene-art/subpage_openings.py', ''
    dt, D, mt, M = PAGES[page]()
    if dt is None:   # legacy page: keep its tuned title settings
        dt, mt = LEGACY[page]['desktop']['title'], LEGACY[page]['mobile']['title']
    folder = ROOT / 'assets' / 'scenes' / page
    folder.mkdir(parents=True, exist_ok=True)
    for l in D + M:
        if l['prop'].startswith('i-'):
            shutil.copyfile(ISL / f"{l['prop'][2:]}.png", folder / f"{l['prop']}.png")
    # Phones: the title ends near the top (y -470 .. -500) right under the
    # breadcrumb, so an island that ends higher than MOBILE_TOP lands on text.
    # Pull such end positions down to just below the title band.
    for l in M:
        if l['prop'].startswith('i-') and l['to']['y'] < MOBILE_TOP:
            l['to'] = dict(l['to'], y=MOBILE_TOP)
    data = {'page': page, 'enabled': True, 'note': NOTE, 'desktop': {'canvas': [1600, 900], 'title': dt, 'layers': D},
            'mobile': {'canvas': [900, 1600], 'title': mt, 'layers': M}}
    (ROOT / 'src' / 'data' / 'scenes' / f'{page}.json').write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')
    return len(D), len(M)


